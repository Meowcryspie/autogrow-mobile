function buildFacility(
  params: Omit<FacilityNode, 'controllers'> & {
    primaryController: Omit<AttachedController, 'id' | 'sensors' | 'linkMode'>;
    extraControllers?: AttachedController[];
  }
): FacilityNode {
  const isAttn = params.primaryController.status === 'ATTENTION';
  const primary: AttachedController = {
    ...params.primaryController,
    id: params.primaryController.serial,
    linkMode: 'DEMO_SAFE',
    sensors: makeDefaultSensors(
      params.id,
      params.metrics.ec,
      params.metrics.ph,
      params.metrics.vpd,
      params.metrics.vwc,
      params.metrics.waterTemp,
      isAttn
    ),
  };

  return {
    id: params.id,
    name: params.name,
    type: params.type,
    zone: params.zone,
    crop: params.crop,
    metrics: params.metrics,
    controllers: [primary, ...(params.extraControllers || [])],
  };
}

